const messages: Record<Locale, Record<string, string>> = { en: {}, 'zh-CN': zhCN, 'zh-TW': zhTW };

let locale = $state<Locale>('en');

export const i18n = {
  get locale() {
    return locale;
  },
};

export function resolveLocale(languages: readonly string[]): Locale {
  for (const language of languages) {
    const normalized = language.toLowerCase();
    if (/^zh(?:-|$)/.test(normalized)) {
      if (/zh-(?:tw|hk|mo|hant)/.test(normalized)) return 'zh-TW';
      return 'zh-CN';
    }
    if (/^en(?:-|$)/.test(normalized)) return 'en';
  }
  return 'en';
}

export function initializeLocale(): void {
  if (!browser) return;
  const stored = localStorage.getItem(storageKey);
  locale =
    stored === 'en' || stored === 'zh-CN' || stored === 'zh-TW'
      ? stored
      : resolveLocale(navigator.languages);
  document.documentElement.lang = locale;
}

export function setLocale(value: Locale): void {
  locale = value;
  if (!browser) return;
  localStorage.setItem(storageKey, value);
  document.documentElement.lang = value;
}

export function t(key: string, variables: Record<string, string | number> = {}): string {
  let message = messages[locale][key] ?? key;
  for (const [name, value] of Object.entries(variables)) {
    message = message.replaceAll(`{${name}}`, String(value));
  }
  return message;
}
